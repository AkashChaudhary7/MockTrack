/**
 * Finds exam from catalog by ID or generates default structure
 */
export function getExamCatalogItem(id: string): ExamProfile | undefined {
  return MASTER_EXAM_CATALOG.find((e) => e.id === id);
}

/**
 * Returns subjects for any exam profile, falling back to default mapping
 */
export function getSubjectsForProfile(profile: ExamProfile): ExamSubjectConfig[] {
  if (profile.subjects && profile.subjects.length > 0) {
    return profile.subjects;
  }

  // Check catalog
  const catalogMatch = MASTER_EXAM_CATALOG.find(
    (c) =>
      c.id === profile.id ||
      c.name.toLowerCase() === profile.name.toLowerCase() ||
      c.shortCode.toLowerCase() === profile.shortCode.toLowerCase()
  );

  if (catalogMatch?.subjects && catalogMatch.subjects.length > 0) {
    return catalogMatch.subjects;
  }

  // Fallback generation based on name
  const name = (profile.name || profile.shortCode || "").toLowerCase();
  const total = profile.totalMarks || 200;

  if (name.includes("dsssb") && name.includes("cs")) {
    return MASTER_EXAM_CATALOG.find((e) => e.id === "dsssb-tgt-cs")!.subjects!;
  }
  if (name.includes("bank") || name.includes("ibps") || name.includes("sbi") || name.includes("rbi")) {
    const subMax = Math.round(total / 3);
    return [
      { id: "gen-quant", name: "Quantitative Aptitude", maxMarks: subMax },
      { id: "gen-reas", name: "Reasoning Ability", maxMarks: subMax },
      { id: "gen-eng", name: "English Language", maxMarks: total - 2 * subMax },
    ];
  }
  if (name.includes("upsc")) {
    return [
      { id: "gen-gs", name: "General Studies Paper 1", maxMarks: Math.round(total / 2) },
      { id: "gen-csat", name: "CSAT Paper 2", maxMarks: total - Math.round(total / 2) },
    ];
  }
  if (name.includes("neet")) {
    return [
      { id: "gen-bio", name: "Biology", maxMarks: 360 },
      { id: "gen-chem", name: "Chemistry", maxMarks: 180 },
      { id: "gen-phy", name: "Physics", maxMarks: 180 },
    ];
  }
  if (name.includes("jee")) {
    return [
      { id: "gen-phy", name: "Physics", maxMarks: 100 },
      { id: "gen-chem", name: "Chemistry", maxMarks: 100 },
      { id: "gen-math", name: "Mathematics", maxMarks: 100 },
    ];
  }

  // Standard 4-section default (SSC / general)
  const quarter = Math.round(total / 4);
  return [
    { id: "gen-quant", name: "Quantitative Aptitude", maxMarks: quarter },
    { id: "gen-reas", name: "General Intelligence & Reasoning", maxMarks: quarter },
    { id: "gen-eng", name: "English Comprehension", maxMarks: quarter },
    { id: "gen-ga", name: "General Awareness", maxMarks: total - 3 * quarter },
  ];
}
